def render_strategy_meta(strategy: dict):
    """Which model wrote the strategy, and whether every figure in it traces back to the data."""
    model = strategy.get("model")
    if model:
        used_fallback = model == fallback_model() and model != primary_model()
        st.caption(
            f"Generated by `{model}`"
            + (" (fallback: the primary model was unavailable)" if used_fallback else "")
        )

    grounding = strategy.get("grounding")
    if grounding is None:
        st.caption("Grounding check unavailable: this strategy was generated before the check existed.")
    elif grounding["total"] == 0:
        st.caption("Grounding check: the strategy text contains no figures to verify.")
    elif not grounding["ungrounded"]:
        st.success(f"All {grounding['total']} figures grounded in the data.", icon=":material/verified:")
    else:
        st.warning(
            f"{len(grounding['ungrounded'])} of {grounding['total']} figures could not be matched "
            "to the data sent to the model: " + ", ".join(grounding["ungrounded"]),
            icon=":material/error:",
        )


def render_strategy(strategy: dict):
    if "raw" in strategy:
        st.warning("Model response wasn't valid JSON — showing raw output.")
        st.text(strategy["raw"])
        return

    st.markdown(f"**{strategy.get('executive_summary', '')}**")
    render_strategy_meta(strategy)

    recs = sorted(
        strategy.get("recommendations", []),
        key=lambda r: PRIORITY_ORDER.get(r.get("priority", "low"), 3),
    )
    for rec in recs:
        priority = rec.get("priority", "low")
        color = PRIORITY_COLORS.get(priority, "#9E9E9E")
        with st.container(border=True):
            st.markdown(
                f"**{rec.get('aspect', '')}** "
                f"<span style='background-color:{color};color:white;padding:2px 8px;"
                f"border-radius:8px;font-size:0.75em;'>{priority.upper()}</span>",
                unsafe_allow_html=True,
            )
            st.markdown(f"*Finding:* {rec.get('finding', '')}")
            st.markdown(f"*Recommendation:* {rec.get('recommendation', '')}")


