"""Markdown for the human-label section of docs/aspect_eval.md (written by scripts/eval_agreement.py)."""

import re
from collections import Counter

from src.evaluation.agreement import (
    LABELS,
    MODES,
    agreement_summary,
    kappa_interpretation,
    precision_rows,
)

BEGIN = "<!-- HUMAN-LABELS:BEGIN (generated by scripts/eval_agreement.py; edit the script, not this block) -->"
END = "<!-- HUMAN-LABELS:END -->"


def _pct(x):
    return "n/a" if x is None else f"{x:.0%}"


def _k(x):
    return "undefined" if x is None else f"{x:.2f}"


def _clip(text: str, n: int) -> str:
    text = re.sub(r"\s+", " ", text or "").replace("|", "/").strip()
    return text if len(text) <= n else text[: n - 1] + "…"


def render_human_block(rows: list, aspects=("ux", "price")) -> str:
    """The generated section. Every number in it comes from `human_label` unless it says otherwise."""
    n_rows = len(rows)
    human = [r for r in rows if (r.get("human_label") or "").strip()]
    lines = [BEGIN, "", "## Results from human labels", ""]

    if not human:
        lines += [
            "**No human labels yet** (`human_label` is empty in all "
            f"{n_rows} rows), so there is nothing here to report. Label the rows with "
            "`streamlit run scripts/label_app.py`, then run `python scripts/eval_agreement.py`. "
            "Every number elsewhere in this document comes from Claude's *draft* labels.",
            "",
            END,
        ]
        return "\n".join(lines)

    lines += [
        f"**Source: human labels** — {len(human)} of {n_rows} rows labelled"
        + ("" if len(human) == n_rows else f" ({n_rows - len(human)} still unlabelled and excluded from the precision below)")
        + ". Draft figures are shown only where the column says so.",
        "",
        "### Precision per mode (human labels)",
        "",
        "| Aspect | Mode | Negative mentions | Human-labelled | Genuine | **Precision (human)** | Draft precision, same rows |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    human_rows = precision_rows(rows, "human_label", aspects)
    labelled_only = [r for r in rows if (r.get("human_label") or "").strip()]
    draft_same_rows = {
        (d["aspect"], d["mode"]): d for d in precision_rows(labelled_only, "draft_label", aspects)
    }
    for r in human_rows:
        d = draft_same_rows[(r["aspect"], r["mode"])]
        lines.append(
            f"| {r['aspect']} | {r['mode']} | {r['negative']} | {r['labelled']} | {r['genuine']} | "
            f"**{_pct(r['precision'])}** | {_pct(d['precision'])} |"
        )

    summary = agreement_summary(rows)
    lines += [
        "",
        "### Agreement between Claude's draft labels and the human labels",
        "",
        f"On the {summary['n']} rows that have both: {summary['agree']} identical "
        f"({summary['agree'] / summary['n']:.0%}).",
        "",
        "| Statistic | Value | Reading |",
        "|---|---:|---|",
        f"| Cohen's κ, 3 classes (genuine / inherited / false_trigger) | {_k(summary['kappa'])} | {kappa_interpretation(summary['kappa'])} |",
        f"| Cohen's κ, genuine vs not genuine | {_k(summary['kappa_binary'])} | {kappa_interpretation(summary['kappa_binary'])} |",
        "",
    ]

    pairs = Counter((r["draft_label"].strip(), r["human_label"].strip()) for r in rows
                    if (r.get("draft_label") or "").strip() and (r.get("human_label") or "").strip())
    labels = LABELS + sorted({h for _, h in pairs} - set(LABELS))
    lines += ["Rows = draft label, columns = human label:", "", "| draft ↓ / human → | " + " | ".join(labels) + " |",
              "|---|" + "---:|" * len(labels)]
    for d in LABELS:
        lines.append(f"| {d} | " + " | ".join(str(pairs.get((d, h), 0)) for h in labels) + " |")

    disagreements = summary["disagreements"]
    lines += ["", f"### Disagreements ({len(disagreements)})", ""]
    if disagreements:
        lines += ["| Review | Aspect | Draft | Human | Draft reason | Context |", "|---|---|---|---|---|---|"]
        for r in disagreements:
            lines.append(
                f"| #{r['review_id']} | {r['aspect']} | {r['draft_label']} | **{r['human_label']}** | "
                f"{_clip(r.get('draft_reason'), 90)} | {_clip(r.get('context_window'), 110)} |"
            )
    else:
        lines.append("None.")
    lines += ["", END]
    return "\n".join(lines)


def splice_block(doc: str, block: str) -> str:
    """Replace the generated block inside `doc` (or append it if the markers aren't there yet)."""
    if BEGIN in doc and END in doc:
        start, end = doc.index(BEGIN), doc.index(END) + len(END)
        return doc[:start] + block + doc[end:]
    return doc.rstrip("\n") + "\n\n" + block + "\n"
